"""**量纲族**判定：单位 ↔ 量纲 ↔ 题干问的量。

🔴 **为什么需要它**（2026-11-09 实测）：
质检的量纲判据原先是"扫描题干里出现了哪些**单位字面**"，
于是两种错法都出现了：

1. **误判**：题干"氩气**浓度**达到什么程度时，可在**数分钟内**导致窒息" ——
   问的量是**浓度**（%），"数分钟内"只是时限条件；
   判据看到"分钟"就认为"题干问分钟" → 报"量纲对不上"（**假的**）。
2. **漏判**：题干问"氮气吹扫**压力**限值"，锚点却含 `71 ℃` / `85 ℃` ——
   题干里没有任何单位字面 → 判据**不报**（真的该报）。

→ 改成**按量纲族**判：
* 题干的**量名**（浓度 / 时间 / 压力 / 长度 / 体积 / 质量 / 温度 / 功率 …）→ 题干量纲族**集合**；
* 锚点的**单位** → 锚点量纲族集合；
* 只有当"锚点族 ∩ 题干族 = ∅"且两边都非空时才报。
  （题干含多个量名时（浓度 + 时间），只要锚点族命中其中**任一个**就不报。）

放在 `src/` 是因为它属于**领域知识**：质检（`tools/review_eval_set.py`）与
锚点修复（`tools/fix_numeric_anchors.py`）都要用同一份判定，
两处各写一套必然打架（K-74 / K-83 的教训）。
"""
from __future__ import annotations

import re

#: 单位 → 量纲族（单位已小写化）。
UNIT_FAMILY: dict[str, list[str]] = {
    "压力": ["mpa", "kpa", "pa", "bar", "兆帕", "千帕", "帕"],
    "长度": ["m", "mm", "cm", "km", "米", "毫米", "厘米", "千米"],
    "面积": ["m2", "m²", "mm2", "mm²", "cm2", "cm²", "平方米", "平方毫米", "平方厘米"],
    "体积": ["m3", "m³", "立方米", "升", "l"],
    "时间": ["h", "min", "分钟", "小时", "秒", "天", "s", "年", "月", "日"],
    "质量": ["kg", "t", "吨", "千克", "mg", "g", "克"],
    "浓度": ["%", "‰", "mg/m3", "mg/m³", "ppm", "mg/mg"],
    "温度": ["℃", "c", "°c"],
    "功率": ["kw", "kva", "mva", "w", "千瓦", "伏安"],
    "数量": ["个", "台", "套", "条", "项", "人", "次"],
}

#: 题干里的**量名** → 量纲族。
#: ⚠️ 顺序有意义：先匹配到的先生效（"罐壁高度" 含 "高度" → 长度）。
QUESTION_FAMILY: list[tuple[str, str]] = [
    ("压力", "压力"), ("压强", "压力"),
    ("长度", "长度"), ("距离", "长度"), ("高度", "长度"),
    ("管径", "长度"), ("直径", "长度"), ("水深", "长度"),
    ("面积", "面积"), ("截面", "面积"),
    # 🔴 **"体积分数"是浓度不是体积**（2026-11-09 修）：
    #    题干"甲烷达到什么**体积分数**范围"，锚点 "25 %" / "30 %"
    #    —— 体积分数就是百分比，判成体积族会**误报量纲不符**。
    ("体积分数", "浓度"), ("质量分数", "浓度"),
    ("容积", "体积"), ("体积", "体积"),
    ("时间", "时间"), ("多久", "时间"), ("小时", "时间"),
    ("分钟", "时间"), ("周期", "时间"), ("供气", "时间"), ("时效", "时间"),
    # 🔴 **"储量"是质量不是体积**（2026-11-09 修）：
    #    题干"甲类物品仓库…其**储量**满足什么条件"，锚点 "5 t"（吨）
    #    —— 判成体积族会**误报量纲不符**。
    # 🔴 **"存量"是体积不是质量**（2026-11-09 manualfix 再修）：
    #    题干"硝酸铵溶液罐区…单个罐区**存量**最高不超1000m3"（m³ 体积）
    #    —— 判成质量族会**误报量纲不符**；"储量"仍留质量族（"5 t"那条）。
    ("重量", "质量"), ("质量", "质量"), ("存量", "体积"), ("装量", "质量"),
    ("储量", "质量"),
    ("浓度", "浓度"), ("含量", "浓度"),
    ("温度", "温度"), ("热度", "温度"),
    ("功率", "功率"), ("负荷", "功率"),
]


def unit_part(x) -> str:
    """从锚点里取**单位部分**（"10 mg/m3" → "mg/m3"、"25 mm" → "mm"）。"""
    s = re.sub(r"^-?\d+(?:\.\d+)?", "", str(x or "").strip()).strip()
    return s.lower()


def number_part(x) -> str:
    """从锚点里取**数值部分**（"10 mg/m3" → "10"）。"""
    m = re.match(r"(-?\d+(?:\.\d+)?)", str(x or "").strip())
    return m.group(1) if m else str(x or "").strip()


def unit_families(unit) -> set[str]:
    """一个单位（或锚点）属于哪些量纲族。"""
    u = unit_part(unit)
    if not u:
        return set()
    return {fam for fam, us in UNIT_FAMILY.items() if u in us}


def question_families(question) -> set[str]:
    """题干问的量纲族集合（可能多个：浓度 + 时间）。"""
    q = question or ""
    out = set()
    for kw, fam in QUESTION_FAMILY:
        if kw in q:
            out.add(fam)
    return out


def dimension_conflict(question, anchors) -> str | None:
    """题干问的量 ↔ 锚点答的量是否**冲突**。

    :returns: 冲突说明（`None` = 不冲突或判不出来）
    """
    qf = question_families(question)
    if not qf:
        return None                      # 题干的量名判不出来 → 交给人工
    af = set()
    for a in anchors or []:
        af |= unit_families(a)
    if not af:
        return None
    if af & qf:
        return None                      # 命中任一量纲族 → 正常
    return (f"题干问「{'/'.join(sorted(qf))}」，"
            f"锚点是「{'/'.join(sorted(af))}」")


def unit_compatible(old, new) -> bool:
    """候选单位是否是原单位的**延伸**（原单位是候选的前缀）。

    🔴 **必须有这条约束**：只按"数值相同"匹配会**跨单位乱配** ——
    实测 `"40 MPa"` 会被配到 `"40 %"`（压力配成百分比），
    而这两者在语义上毫无关系。

    → 允许的形态：**原单位被截断**（"10 m" ← "10 mg/m3"）、平方化（"25 mm" ← "25 mm2"）。
    """
    o, n = unit_part(old), unit_part(new)
    if not o:
        return False
    return n.startswith(o)
