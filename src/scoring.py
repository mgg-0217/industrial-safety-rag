# numeric_exact_match_rate
# ---------------------------------------------------------------------------

def numeric_hits(answer, must_include_numbers):
    """返回 ``(命中数, 总数, 明细)``。

    🔴 `must_include_numbers` 是**`;` 分隔的字符串**（如 ``"19.5 %;21 %"``），
    不是 JSON 数组 —— 实测踩过。

    🔴 K-43：**答案侧也要折单位**。
    语料里的数值带 ASCII 单位（"0.5t"、"500 mm"），
    模型回答用中文单位（"0.5吨"、"500毫米"）——
    只折 key 侧的话两边形态还是对不上。
    """
    raw = must_include_numbers
    if isinstance(raw, str):
        items = [x for x in re.split(r"[;；]", raw) if x.strip()]
    else:
        items = [str(x) for x in (raw or []) if str(x).strip()]
    a = N.match_num_norm(answer or "")
    hits = []
    for it in items:
        n = N.normalize_number(it)
        hits.append(bool(n) and n in a)
    return sum(hits), len(items), [{"number": it, "hit": h}
                                   for it, h in zip(items, hits)]


