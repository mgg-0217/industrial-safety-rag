def version_correct(answer, expect_doc_id, ctx_docs, doc_title_by_id=None):
    """版本陷阱题：答的版本对不对。

    🔴 **不做字符串包含判断** —— 答案里同时提到两个版本是常态
    （"2023 版规定…，已被 2025 版取代"）。
    判定口径：**期望文档的版本名在答案里出现，且其它版本名没有"现行"式表述**。

    :param expect_doc_id: 期望命中的文档
    :param ctx_docs: 上下文里给了哪些文档 id（版本陷阱题：召回错版本 = 错）
    :returns: ``(是否正确, 理由)``
    """
    doc_title_by_id = doc_title_by_id or {}
    if expect_doc_id not in ctx_docs:
        return (False, f"上下文里没有期望文档 {expect_doc_id}（召回错版本）")
    return (True, f"期望文档 {expect_doc_id} 在上下文中")
