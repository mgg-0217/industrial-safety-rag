#: 「转炉**是否**属于相关有限空间，**应结合**其结构、进出条件、通风状况判断」
#: —— 这是在说"要判断得看条件"，**不是**在给转炉下规定。
#: 但它含主体 + 断言谓语（"属于"/"应"）→ 旧判据判成污染（假阳性）。
#:
#: ⚠️ 代价：真正写成条件式的污染（「T-9041 是否属于受限空间作业，应按…执行」）
