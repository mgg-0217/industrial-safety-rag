#: **句级**否定/限定标记 —— 判断某句是不是**在给主体下规定**。
#:
#: 🔴 这份清单与 PRD 7.1 表格第 2 行对齐：**"带明确限定地引用别处条款 → 通过"**。
#: 句子只要沾了这些标记之一，就是在说"这条对主体不适用 / 还没法确定 / 要补资料"，
#: 而不是**给主体下了一条规定**。
#:
#: 🔴🔴 踩过的坑（K-39）：**枚举否定词是死路**。
#: 第一版清单（未/没有/无/查不到/未见/缺乏/不适用）漏掉了"不能""需补充""如需"
#: "仍需""未给出"这些模型**实际会写**的说法，
#: 于是一条**完全正确**的拒答被判成"误答"：
#: 「资料仅要求对设备定期巡回检查并建立定期检查记录，但**未给出** T-9001 的具体检修周期」
#: → 句中有主体、句中无清单里的否定词 → 被当成"给主体下了规定"。
#:
#: → 改用**正则覆盖整个词族**（"未/没有/无 + 动词"），
#: 词族能覆盖模型的各种写法，而不是靠一个个补词。
#:
#: 🔴 刻意**不**把"不得""不允许"当否定标记 ——
#: "T-9001 不得带病运行"是在**给主体下规定**（该判误答），
#: 不是在表达"没有规定"。
#:
#: 🔴 但**句级**这一层用"宽"的：句子里出现"未/无/没有"就该认为该句在讲缺失，
#: 不必纠结后面接的到底是什么词。
_NEG_PATTERN = re.compile(
    # 🔴 `\s*` 不是可有可无：模型写「语料中无 T-9001 的相关规定」时，
    #    "无"后面隔着一个空格 —— 不允许空格的话这句会被当成肯定句（K-39）。
    # 🔴 **字符类必须覆盖中文引号/书名号/括号**（2026-11-05 实测修正）：
    #    模型写「资料中**没有**“聚丙烯装置”的专门规定」时，
    #    "没有"后面紧跟的是全角引号 `“` → 旧字符类 `[一-龥A-Za-z0-9]` 不含它
    #    → **否定句被判成肯定句** → 假阳性污染。
    #    这是"正则字符类没覆盖模型真实输出"的典型坑（与 K-39 同款）。
    r"未(?!来|免)\s*[一-龥A-Za-z0-9“”‘’\"'《》【】（）()]"   # 未给出 / 未提供 / 未规定 …
    r"|没有\s*[一-龥A-Za-z0-9“”‘’\"'《》【】（）()]"        # 没有规定 / 没有说明 …
    r"|无(?!论)\s*[一-龥A-Za-z0-9“”‘’\"'《》【】（）()]"     # 无规定 / 无相关 …
    # 🔴 补 "属于|是|针对"：模型澄清归属时会写
    #    「该原文针对游乐设施，**不属于**乙烯裂解装置的专门要求」
    #    「该模板仅是受限空间模板，**不是**电除尘器的专门规定」
    #    旧词表只认"不适用/不明确/…" → 这两句被判成污染（假阳性）。
    r"|不(?:适用|存在|明确|确定|足|能|会|含|包括|据|得|宜|予|同|符|属于|是|针对)"
    r"|并非|并不|尚未|暂无|暂未|无从|没法|不足以|缺乏|缺少"
    r"|需(?:要)?(?:补充|提供|澄清|确认|进一步|说明)|尚需|如需|仍需|还需|有待"
    r"|待(?:补充|提供|确认)|应澄清"
    # 条件 / 限定（PRD 7.1 表格第 2 行的"带明确限定"）：
    # 「若 T-9001 检维修涉及受限空间等特殊作业，还应执行相应特殊作业安全规范」
    # 是在说"满足这个条件才适用"，不是在说"T-9001 有这么条规定"。
    r"|若|如果|假如|倘若|凡"
)

#: 🔴 **条件式 / 待定表述**（2026-11-05 实测修正）。
