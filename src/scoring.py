# ---------------------------------------------------------------------------
# 置信区间
# ---------------------------------------------------------------------------

def wilson(successes, n, z=1.96):
    """Wilson 置信区间（小样本比正态近似稳）。"""
    if n == 0:
        return (0.0, 0.0, 0.0)
    p = successes / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    m = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    lo = (c - m) / d
    hi = (c + m) / d
    return (round(p, 4), round(max(0.0, lo), 4), round(min(1.0, hi), 4))


# ---------------------------------------------------------------------------
# key_point_coverage
# ---------------------------------------------------------------------------

def _bigrams(s):
    """字符二元组集合。"""
    return {s[i:i + 2] for i in range(len(s) - 1)}


def bigram_coverage(kp, answer):
    """key_point 的字符二元组在答案里的覆盖率（**顺序无关**）。

    :returns: ``0.0``–``1.0``；key_point 少于 2 字返回 0
    """
    if not kp or len(kp) < 2:
        return 0.0
    kb = _bigrams(kp)
    if not kb:
        return 0.0
    return len(kb & _bigrams(answer)) / len(kb)


def key_point_hits(answer, key_points, soft=True, threshold=0.7):
    """返回 ``(命中数, 总数, 每个 key_point 的命中明细)``。

    🔴 匹配用 `normalize.match_norm()`（标点折叠 + 去空白 + 小写，K-35）——
    直接逐字匹配只有 45% 命中，会把"说对了但写法不同"判成错。

    ## 为什么还要一层"软匹配"（K-42）

    M2 把 key_point **对齐成原文片段**（最长公共子串），
    目的是让"命中"这件事**可复核**（答案里必须真的出现这段原文）。
    但对齐产物有两个副作用：

    1. **片段很短**（实测中位数 10 字，最短 2 字），
       于是它常被**从短语中间切断**（"试生产前企业开"）；
    2. **带着原文的列表符号**（"a.作业人员…"、"(六)生产经"、"10.当"）。

    实测未命中的分类（真实运行产物，309 条未命中）：

    | 类别 | 条数 | 占比 |
    |---|---|---|
    | 改写 / 换词（语序、单位写法不同） | 193 | 62% |
    | 片段过短（< 6 字，多是数值残片） | 55 | 18% |
    | 仅列表符号差异 | 22 | 7% |
    | 模型整体拒答 | 39 | 13% |

    → **87% 的未命中是"判定口径 × 对齐产物"的交互，不是模型答错**。
    严格字面包含率因此**不能直接当作模型能力指标**引用
    （实测只有 16.8%–21.8%）。

    → 本函数同时给两把尺子：
      - **严格**（`kp ⊆ answer`）：可复核、保守，保留在明细里；
      - **软**（二元组覆盖率 ≥ ``threshold``，顺序无关）：容忍语序与写法差异。

    🔴 **两把尺子都要报**，不合并、不换算 —— 合并会掩盖口径差异，
    只报一个则等于偷偷挑对自己有利的那个。

    :param soft: 是否启用软匹配
    :param threshold: 软匹配的二元组覆盖率阈值（实测 0.6/0.7/0.8 三档都要报）
    """
    a = N.match_norm(answer or "")
    kps = list(key_points or [])
    detail = []
    for kp in kps:
        k = N.match_norm(kp)
        strict = bool(k) and k in a
        cov = bigram_coverage(k, a) if k else 0.0
        # 少于 4 个字的片段不做软匹配 —— "15m"、"1m" 这种数值残片
        # 靠字符二元组匹配毫无意义（数值题另有 must_include_numbers 这个锚点）
        soft_hit = (not strict) and soft and len(k) >= 4 and cov >= threshold
        detail.append({"key_point": kp, "hit": bool(strict or soft_hit),
                       "strict": bool(strict), "cov": round(cov, 3),
                       "klen": len(k)})
    return sum(1 for d in detail if d["hit"]), len(kps), detail


